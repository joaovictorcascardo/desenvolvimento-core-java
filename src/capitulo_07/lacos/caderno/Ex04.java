package capitulo_07.lacos.caderno;

import java.util.Scanner;

public class Ex04 {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int entrada = sc.nextInt();
        for (int i = 0; i <= entrada; i++) {
            int valorAtual = i;
            System.out.println(valorAtual);
        }
    }
}
